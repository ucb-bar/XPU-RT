HEADER = "/* @generated by qnn_models/flow_c/flowc/emit_runtime.py — do not edit. */"


def _lane_key(e: FlowCEntry, mode: str) -> str:
    return e.kind if mode == "kind" else f"{e.kind}|{e.network}"


def _c_str(s: str) -> str:
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def emit_table(entries: list[FlowCEntry], lane_mode: str, out_path: str) -> dict:
    lanes: "OrderedDict[str, dict]" = OrderedDict()
    for e in entries:
        key = _lane_key(e, lane_mode)
        if key not in lanes:
            lanes[key] = {"kind": e.kind, "label": e.backend_label,
                          "hart": e.hart, "network": e.network,
                          "serialized": e.exec_serialized,
                          "spin_us": e.gate_spin_us,
                          "fifo": e.sched_fifo_prio}
    lane_index = {k: i for i, k in enumerate(lanes)}

    lines = [HEADER, "#pragma once", "#include <stddef.h>", "",
             "#ifdef __cplusplus", 'extern "C" {', "#endif", ""]
    lines += [
        "/* The first block is field-for-field modelblaster's xpurt_sched_entry_t",
        " * (pipeline/ingest_xpurt_schedule.py) so a reader of one table can read",
        " * the other; the second block is what a QNN dispatch additionally needs. */",
        "typedef struct {",
        "    int          entry_id;",
        "    const char  *network;",
        "    int          instance;",
        "    int          dispatch_id;      /* binding id == coarse-IR dispatch_id */",
        "    const char  *op;               /* IR op kind: always \"qnn_graph\" here */",
        "    const char  *name;             /* binding name */",
        "    const char  *core_kind;        /* registry kind: hta / dsp / cpu */",
        "    int          hart;             /* host core this lane pins to */",
        "    double       start_time_ms;",
        "    double       duration_ms;",
        "    int          n_deps;",
        "    const int   *deps;",
        "    int          time_dep_entry_id;",
        "    /* ---- Flow C ---- */",
        "    const char  *backend_label;    /* HTA / DSP / CPU — profile-side label */",
        "    const char  *backend_lib;      /* libQnn*.so to dlopen */",
        "    const char  *ctx;              /* context binary filename */",
        "    const char  *graph;            /* graph inside that context */",
        "    int          exec_serialized;  /* backend needs a process-wide exec lock */",
        "    int          lane;             /* worker lane index */",
        "    int          n_ir_ops;         /* IR ops this tile covers */",
        "    int          ir_first;",
        "    int          ir_last;",
        "} flowc_sched_entry_t;",
        "",
        f"#define FLOWC_N_ENTRIES {len(entries)}",
        f"#define FLOWC_N_LANES {len(lanes)}",
        "",
    ]
    for e in entries:
        if e.deps:
            lines.append(f"static const int flowc_e{e.entry_id}_deps[] = "
                         f"{{ {', '.join(str(d) for d in e.deps)} }};")
    lines.append("")
    lines.append("static const flowc_sched_entry_t FLOWC_TABLE[FLOWC_N_ENTRIES] = {")
    for e in entries:
        deps_ref = f"flowc_e{e.entry_id}_deps" if e.deps else "NULL"
        lines.append(
            f"    {{ {e.entry_id}, {_c_str(e.network)}, {e.instance}, {e.binding_id}, "
            f'"qnn_graph", {_c_str(e.binding_name)}, {_c_str(e.kind)}, {e.hart}, '
            f"{e.start_time_ms:.6f}, {e.duration_ms:.6f}, "
            f"{len(e.deps)}, {deps_ref}, {e.time_dep}, "
            f"{_c_str(e.backend_label)}, {_c_str(e.backend_lib)}, "
            f"{_c_str(e.ctx)}, {_c_str(e.graph)}, {1 if e.exec_serialized else 0}, "
            f"{lane_index[_lane_key(e, lane_mode)]}, {e.n_ir_ops}, {e.ir_first}, {e.ir_last} }},")
    lines.append("};")
    lines.append("")
    lines.append("static const char *const FLOWC_LANE_NAME[FLOWC_N_LANES] = {")
    for key in lanes:
        lines.append(f"    {_c_str(key)},")
    lines.append("};")
    lines.append("static const int FLOWC_LANE_HART[FLOWC_N_LANES] = { "
                 + ", ".join(str(v["hart"]) for v in lanes.values()) + " };")
    lines.append("/* Spin-before-deadline budget per lane, from the registry's "
                 "qnn.gate_spin_us. */")
    lines.append("static const long FLOWC_LANE_SPIN_US[FLOWC_N_LANES] = { "
                 + ", ".join(str(v["spin_us"]) for v in lanes.values()) + " };")
    lines.append("/* SCHED_FIFO priority per lane (0 = leave the lane on SCHED_OTHER), "
                 "from the registry's qnn.sched_fifo_prio. */")
    lines.append("static const int FLOWC_LANE_FIFO[FLOWC_N_LANES] = { "
                 + ", ".join(str(v["fifo"]) for v in lanes.values()) + " };")
    lines.append("")
    lines += ["#ifdef __cplusplus", "}  /* extern \"C\" */", "#endif", ""]

    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "w") as f:
        f.write("\n".join(lines))
    return {"lanes": list(lanes), "lane_index": lane_index, "n_entries": len(entries)}

