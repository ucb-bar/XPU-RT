"""Stage 5 — codegen: the QNN back end of the flow.

ModelBlaster's `generate_xpurt_main.py` emits Zephyr C that calls
generated kernels through a hart-pinned `modelblaster_pool`.  That pool is
a *parallel-for*: one op, N harts, a range split.  It is the right shape
for RISC-V, and the wrong shape here — on this board the work inside a
dispatch is done by HVX / the tensor accelerator / the CPU op package,
none of which the host runtime can subdivide.

So Flow C emits a different runtime over the same table:

  threading   One lane worker per machine kind (`--lane-mode kind`), or per
              (kind, network) (`--lane-mode kind-network`) when the schedule
              serialises two networks onto one kind and their periods differ
              enough that head-of-line blocking would eat a deadline.  Each
              worker is a std::thread pinned with pthread_setaffinity_np to
              the core the registry gives that kind.  Workers block inside
              QnnGraph_execute, so the lane count is the concurrency: three
              lanes = HTA + DSP + CPU running at once, which is the whole
              point of the schedule.

  tiling      A tile is a binding — a contiguous IR op range compiled into
              one QNN graph.  The runtime executes exactly one graph per
              entry, so re-tiling is a compile-time decision (see
              flowc/bindings.py).  Instance-level tiling falls out for free:
              two instances of the same network may carry different
              backends, and each (ctx, backend) pair is brought up once.

  ordering    Per-entry POSIX completion semaphores, the schedule's
              intra-job `deps[]` and cross-job `time_dep`, and a start-time
              gate against the run's t0.

  serialization  Backends flagged `exec_serialized` in the registry (HTA,
              DSP — their drivers keep process-global state) take a
              per-backend mutex around execute; per-graph mutexes always
              apply because two entries sharing a graph share its I/O
              buffers.
"""

from __future__ import annotations

import os
